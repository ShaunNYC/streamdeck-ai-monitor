import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { AgentFolderAccess } from "../packages/app/src/agent-folder-access.ts";

const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "agent-pulse-mas-access-"));
try {
 const store = path.join(temporary, "access.json");
 const first = path.join(temporary, "first");
 const second = path.join(temporary, "second");
 fs.mkdirSync(first); fs.mkdirSync(second);
 const active = new Set<string>();
 const start = (bookmark: string) => {
  if (bookmark === "revoked") throw new Error("Revoked access");
  active.add(bookmark);
  return () => { active.delete(bookmark); };
 };
 const access = new AgentFolderAccess(store, start);
 access.restore();
 assert.deepEqual(access.paths(), {}, "No implicit grants on first launch");
 access.set("codex", first, "first-bookmark");
 assert.deepEqual(access.paths(), { codex: first }, "Renderer receives paths, never bookmarks");
 assert.equal(fs.statSync(store).mode & 0o777, 0o600);
 access.set("codex", second, "second-bookmark");
 assert.deepEqual([...active], ["second-bookmark"], "Replacing a folder releases its old scope");
 assert.throws(() => access.set("codex", first, "revoked"));
 assert.equal(access.get("codex"), second, "Failed replacement preserves previous grant");
 assert.throws(() => access.set("codex", path.join(temporary, "missing"), "missing"));
 assert.deepEqual([...active], ["second-bookmark"], "Failed path validation releases new scope");
 access.close();
 assert.equal(active.size, 0, "Quit releases all access");
 access.restore();
 assert.equal(access.get("codex"), second, "Restart restores persisted access");
 access.set("claude", first, "claude-bookmark");
 access.revoke("codex");
 assert.equal(access.get("codex"), undefined);
 assert.equal(access.get("claude"), first, "Revoking one agent preserves the other's grant");
 assert.deepEqual([...active], ["claude-bookmark"]);
 access.close();
 access.restore();
 assert.equal(access.get("codex"), undefined, "Revoked grant must not return after restart");
 assert.equal(access.get("claude"), first);
 access.set("claudeDesktop", second, "desktop-bookmark");
 access.revokeAll();
 assert.equal(active.size, 0, "Clear integration releases all live scopes");
 access.restore();
 assert.deepEqual(access.paths(), {}, "Clear integration permanently removes saved grants");
 assert.deepEqual(JSON.parse(fs.readFileSync(store, "utf8")), {});
 access.close();
 fs.writeFileSync(store, JSON.stringify({ codex: { path: second, bookmark: "revoked" }, claude: { path: "relative", bookmark: "unsafe" } }));
 access.restore();
 assert.deepEqual(access.paths(), {}, "Revoked and malformed grants fail closed");
 assert.equal(active.size, 0);
 fs.writeFileSync(store, "broken JSON");
 access.restore();
 assert.deepEqual(access.paths(), {});
 console.log("MAS folder access regression passed");
} finally { fs.rmSync(temporary, { recursive: true, force: true }); }
